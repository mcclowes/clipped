import AppKit
import Foundation
import Observation
import os

/// Industry-standard pasteboard types set by apps to flag content that should be skipped.
/// See https://nspasteboard.org
let concealedPasteboardType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
private let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
private let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
private let legacyTransientType = NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType")

private let skippableNSPasteboardTypes: Set<NSPasteboard.PasteboardType> = [
    transientType,
    autoGeneratedType,
    legacyTransientType,
]

/// Polls for external pasteboard changes and emits items decoded by `PasteboardReader`.
/// Owns the polling lifecycle and change-count baseline used to suppress our own writes.
@MainActor
@Observable
final class PasteboardMonitor {
    private static let logger = Logger(subsystem: "com.mcclowes.clipped", category: "PasteboardMonitor")

    /// Event payload handed to the pipeline.
    struct NewItemEvent {
        let item: ClipboardItem
        let bundleID: String?
        let hasConcealedType: Bool
    }

    private(set) var isMonitoring = false

    /// Invoked on the main actor whenever the monitor observes new pasteboard content.
    var onNewItem: ((NewItemEvent) -> Void)?

    let pasteboard: PasteboardProtocol
    private let reader: PasteboardReader
    /// Not observable (an implementation detail); `nonisolated(unsafe)` lets the nonisolated
    /// `deinit` invalidate it. Only ever mutated on the main actor, and by deinit no other
    /// reference to this monitor survives, so the access is race-free.
    @ObservationIgnored nonisolated(unsafe) var pollTimer: Timer?
    private var lastChangeCount: Int

    private static let pollInterval: TimeInterval = 0.5
    nonisolated static let maxImageBytes = PasteboardReader.maxImageBytes

    init(pasteboard: PasteboardProtocol = NSPasteboard.general) {
        self.pasteboard = pasteboard
        reader = PasteboardReader(pasteboard: pasteboard)
        lastChangeCount = pasteboard.changeCount
    }

    deinit {
        // The run loop retains a repeating Timer, so without this the timer outlives the monitor
        // and keeps firing (against a nil `self`) for the rest of the process.
        pollTimer?.invalidate()
    }

    // MARK: - Lifecycle

    func startMonitoring() {
        guard !isMonitoring else { return }
        Self.logger.debug("Starting clipboard monitoring")
        isMonitoring = true
        // Install on `.common` modes so polling keeps running during menu tracking / window
        // resizes (a plain `scheduledTimer` uses `.default` and stalls in those loops). A 50%
        // tolerance lets the scheduler coalesce the 2 Hz wakeups to cut energy impact.
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.checkIfMonitoring()
            }
        }
        timer.tolerance = Self.pollInterval * 0.5
        RunLoop.main.add(timer, forMode: .common)
        pollTimer = timer
    }

    func stopMonitoring() {
        Self.logger.debug("Stopping clipboard monitoring")
        isMonitoring = false
        pollTimer?.invalidate()
        pollTimer = nil
    }

    /// Re-baseline to the current pasteboard state. Call after initial history load so
    /// the pasteboard content at launch is not treated as a new copy.
    func resetBaseline() {
        lastChangeCount = pasteboard.changeCount
    }

    /// Write to the pasteboard without triggering our own monitoring as a new copy.
    /// Updates the change-count high-water mark so the next poll ignores our own write.
    func write(_ body: (PasteboardProtocol) -> Void) {
        body(pasteboard)
        lastChangeCount = pasteboard.changeCount
    }

    // MARK: - Polling

    /// A timer's queued actor hop can outlive stopMonitoring().
    func checkIfMonitoring() {
        guard isMonitoring else { return }
        check()
    }

    /// Run one poll cycle. Exposed as `internal` so tests can drive the monitor deterministically
    /// without waiting for the `Timer`.
    func check() {
        // MainActor is serial; no re-entrancy guard needed.
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return }
        // A delta > 1 means writes arrived faster than the poll rate and were coalesced
        // into a single observed change — useful for spotting missed clipboard events.
        let changeDelta = currentCount - lastChangeCount
        lastChangeCount = currentCount
        Signposts.clipboard.emitEvent("PasteboardChange", "delta: \(changeDelta)")

        // Skip content flagged by nspasteboard.org convention as transient or auto-generated.
        let types = pasteboard.types ?? []
        if types.contains(where: { skippableNSPasteboardTypes.contains($0) }) {
            return
        }

        let frontmostApp = NSWorkspace.shared.frontmostApplication
        let bundleID = frontmostApp?.bundleIdentifier
        let hasConcealedType = types.contains(concealedPasteboardType)

        guard let item = reader.read(
            appName: frontmostApp?.localizedName,
            bundleID: bundleID
        ) else { return }

        onNewItem?(NewItemEvent(
            item: item,
            bundleID: bundleID,
            hasConcealedType: hasConcealedType
        ))
    }
}
